"""
Public Health Signal Fusion Agent - Gemini Contract Models
Strict input payload and strict JSON output schema models for Gemini 2.5 Flash.
"""

from dataclasses import dataclass, field
from typing import Any, Dict, List, Optional


@dataclass
class GeminiReasoningInput:
    """Read-only data package provided to Gemini Reasoning Agent."""
    cycle_id: str
    timestamp: str
    affected_district: str
    overall_risk_score: float
    confidence_score: float
    risk_level: str
    district_ranking: List[Dict[str, Any]]  # List of dicts with district name, risk, rank
    signal_breakdown: Dict[str, Dict[str, Any]]  # Per-source score + status
    raw_evidence_summary: List[str]  # Bullet points of key raw observations


