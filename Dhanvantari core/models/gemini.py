@dataclass
class GeminiReasoningOutput:
    """Parsed response object matching PRD Section 6 JSON contract."""
    risk_level: str
    confidence: float
    affected_district: str
    reasoning_trace: List[str]
    recommendations: List[str]
    incident_summary: str
    public_advisory: str = ""
    dos_and_donts: Dict[str, List[str]] = field(default_factory=dict)
    whatsapp_message: str = ""
    incident_report: str = ""
    resource_summary: str = ""
